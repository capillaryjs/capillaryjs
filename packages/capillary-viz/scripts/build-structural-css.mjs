import {mkdir, writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'

import {createCapillaryUiRuntime} from '@capillaryjs/capillary-ui'

import {BlockGraph} from '../src/components/BlockGraph.tsx'
import {CategoryHidePanel} from '../src/components/CategoryHidePanel.tsx'
import {LineGraph} from '../src/components/LineGraph.tsx'
import {SplitSelectionPanel} from '../src/components/SplitSelectionPanel.tsx'

const runtime = createCapillaryUiRuntime()
for (const component of [
    BlockGraph,
    CategoryHidePanel,
    LineGraph,
    SplitSelectionPanel,
]) runtime.registerStyles(component)

const outputPath = fileURLToPath(new URL('../styles/structural.css', import.meta.url))
await mkdir(fileURLToPath(new URL('../styles', import.meta.url)), {recursive: true})
await writeFile(
    outputPath,
    '/* Generated by scripts/build-structural-css.mjs. Do not edit directly. */\n\n'
        + `${runtime.styleRegistry.generateCSS()}\n`,
)
console.log(`[capillary-viz] structural CSS: ${outputPath}`)
