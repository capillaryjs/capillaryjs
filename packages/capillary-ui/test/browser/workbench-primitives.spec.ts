test('action menu escapes clipping and supports keyboard, typeahead, disabled items and focus handoff', async ({page}) => {
    await page.setViewportSize({width: 375, height: 700})
    const trigger = page.getByRole('button', {name: 'Create definition'})
    await trigger.focus(); await page.keyboard.press('Enter')
    const menu = page.getByRole('menu', {name: 'Create definition'})
    await expect(menu).toBeVisible()
    await expect(page.getByRole('menuitem', {name: 'Class', exact: true})).toBeFocused()
    expect(await menu.evaluate(element => element.matches(':popover-open'))).toBe(true)
    const bounds = (await menu.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(7)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(368)
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('menuitem', {name: 'Type', exact: true})).toBeFocused()
    await page.keyboard.press('Enter'); await expect(menu).toBeVisible()
    await page.keyboard.press('e')
    await expect(page.getByRole('menuitem', {name: 'Enumeration'})).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(menu).not.toBeVisible(); await expect(trigger).toBeFocused()
    await page.keyboard.press('ArrowUp')
    await expect(page.getByRole('menuitem', {name: 'Save', exact: true})).toBeFocused()
    await page.keyboard.press('Home'); await page.keyboard.press('Space')
    await expect(menu).not.toBeVisible()
    await expect(page.getByRole('textbox', {name: 'After menu'})).toBeFocused()
    await expect(trigger).not.toHaveAttribute('aria-busy')
})

test('menu Tab and outside dismissal do not trap or steal focus', async ({page}) => {
    const trigger = page.getByRole('button', {name: 'Create definition'})
    const menu = page.getByRole('menu')
    await trigger.click(); await page.keyboard.press('Tab')
    await expect(menu).not.toBeVisible()
    await expect(page.getByRole('textbox', {name: 'After menu'})).toBeFocused()
    await trigger.click(); await page.keyboard.press('Shift+Tab')
    await expect(menu).not.toBeVisible()
    await expect(page.getByRole('textbox', {name: 'Before menu'})).toBeFocused()
    await trigger.click(); await page.getByRole('textbox', {name: 'After menu'}).click()
    await expect(menu).not.toBeVisible()
    await expect(page.getByRole('textbox', {name: 'After menu'})).toBeFocused()
})

test('menu command outcomes remain visible after close with scoped delayed feedback and recovery', async ({page}) => {
    const trigger = page.getByRole('button', {name: 'Create definition'})
    const menu = page.getByRole('menu')
    await trigger.click(); await page.getByRole('menuitem', {name: 'Save', exact: true}).click()
    await expect(menu).not.toBeVisible()
    await expect(trigger).toHaveAttribute('aria-busy', 'true')
    await expect(trigger).toHaveAttribute('data-cap-busy-visible', '')
    await expect(trigger).toBeEnabled()
    await trigger.click()
    await expect(page.getByRole('menuitem', {name: 'Save', exact: true})).toHaveAttribute('aria-disabled', 'true')
    await expect(page.getByRole('menuitem', {name: 'Class', exact: true})).not.toHaveAttribute('aria-busy')
    await page.keyboard.press('Escape')
    await page.getByRole('button', {name: 'Fail menu action'}).click()
    await expect(trigger).not.toHaveAttribute('aria-busy')
    await expect(trigger).toHaveAttribute('aria-invalid', 'true')
    await expect(page.locator('cap-menubutton > cap-button cap-error')).toHaveAccessibleName('Menu operation failed')
    await trigger.click(); await page.getByRole('menuitem', {name: 'Save', exact: true}).click()
    await page.getByRole('button', {name: 'Finish menu action'}).click()
    await expect(trigger).not.toHaveAttribute('aria-invalid')
    await expect(trigger).not.toHaveAttribute('aria-busy')
})

