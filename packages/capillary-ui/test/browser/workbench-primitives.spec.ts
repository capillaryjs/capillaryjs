test('native form validation, Enter and submitter policy invoke once with scoped pending and errors', async ({page}) => {
    const save = page.getByRole('button', {name: 'Save details', exact: true})
    const draft = page.getByRole('button', {name: 'Save draft', exact: true})
    const submitted = page.getByRole('status', {name: 'Submitted details'})
    await save.click()
    await expect(submitted).toHaveText('None')
    await page.getByRole('textbox', {name: 'Name', exact: true}).fill('Ada')
    await page.getByRole('textbox', {name: 'Description', exact: true}).fill('First line\nZero: 0; false')
    await page.getByRole('textbox', {name: 'Name', exact: true}).press('Enter')
    await expect(submitted).toHaveText(JSON.stringify({name: 'Ada', description: 'First line\nZero: 0; false', intent: 'save'}))
    await expect(page.getByRole('status', {name: 'Form invocations'})).toHaveText('1')
    await expect(save).toHaveAttribute('aria-busy', 'true')
    await expect(draft).not.toHaveAttribute('aria-busy')
    await expect(save).toBeDisabled(); await expect(draft).toBeDisabled()
    await expect(page.getByRole('textbox', {name: 'Name', exact: true})).toBeEnabled()
    await expect(page.getByRole('button', {name: 'Cancel details'})).toBeEnabled()
    await page.getByRole('textbox', {name: 'Name', exact: true}).press('Enter')
    await expect(page.getByRole('status', {name: 'Form invocations'})).toHaveText('1')
    await page.getByRole('button', {name: 'Fail form action'}).click()
    await expect(save).not.toHaveAttribute('aria-busy')
    await expect(save).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByRole('alert')).toHaveText('Details could not be saved')
    await expect(save).toHaveAccessibleDescription('Details could not be saved')
    await save.click(); await page.getByRole('button', {name: 'Finish form action'}).click()
    await expect(save).not.toHaveAttribute('aria-invalid')
    await expect(page.getByRole('status', {name: 'Form invocations'})).toHaveText('2')
    await page.getByRole('textbox', {name: 'Name', exact: true}).fill('')
    await draft.click()
    await expect(submitted).toContainText('"intent":"draft"')
    await expect(page.getByRole('status', {name: 'Form invocations'})).toHaveText('3')
    await expect(draft).toHaveAttribute('aria-busy', 'true')
    await expect(save).not.toHaveAttribute('aria-busy')
    await page.getByRole('button', {name: 'Finish form action'}).click()
})

test('multiline editing retains native keyboard/selection and field help/error associations at narrow widths', async ({page}) => {
    await page.setViewportSize({width: 375, height: 700})
    const name = page.getByRole('textbox', {name: 'Name', exact: true})
    const area = page.getByRole('textbox', {name: 'Description', exact: true})
    await expect(area).toHaveAccessibleDescription('Plain multiline text')
    expect(await area.evaluate(element => (element as HTMLTextAreaElement).rows)).toBe(4)
    await area.fill('Alpha'); await area.press('End'); await area.press('Enter'); await area.press('b')
    await expect(area).toHaveValue('Alpha\nb')
    await expect(page.getByRole('status', {name: 'Submitted details'})).toHaveText('None')
    await area.evaluate(element => (element as HTMLTextAreaElement).setSelectionRange(1, 4))
    await page.getByRole('button', {name: 'Toggle field validation'}).click()
    expect(await area.evaluate(element => [(element as HTMLTextAreaElement).selectionStart, (element as HTMLTextAreaElement).selectionEnd])).toEqual([1, 4])
    await expect(name).toHaveAttribute('aria-invalid', 'true')
    await expect(name).toHaveAccessibleDescription('Enter a unique name Name already exists')
    expect((await area.boundingBox())!.width).toBeLessThanOrEqual(375)
    const results = await new AxeBuilder({page}).include('section[aria-label="Native form fixture"]').analyze()
    expect(results.violations).toEqual([])
})

test('combobox search, active choice and form value remain separate with native keyboard editing', async ({page}) => {
    const input = page.getByRole('combobox', {name: 'Local choice'})
    await input.fill('be')
    await expect(page.getByRole('option', {name: 'Beta', exact: true})).toBeVisible()
    await expect(input).toBeFocused()
    await expect(input).not.toHaveAttribute('aria-busy')
    await expect(page.getByRole('status', {name: 'Option requests'})).toHaveText('1')
    await expect(page.getByRole('status', {name: 'Local selected value'})).toHaveText('a')
    expect(await page.getByRole('form', {name: 'Choice serialization'}).evaluate(element => new FormData(element as HTMLFormElement).get('choice'))).toBe('a')
    expect(await input.evaluate(element => {
        const event = new KeyboardEvent('keydown', {key: 'Home', bubbles: true, cancelable: true})
        element.dispatchEvent(event)
        return event.defaultPrevented
    })).toBe(false)
    await input.press('ControlOrMeta+ArrowLeft')
    expect(await input.evaluate(element => (element as HTMLInputElement).selectionStart)).toBe(0)
    await input.press('Escape'); await expect(input).toHaveValue('Alpha')
    await input.press('ArrowDown'); await input.press('ArrowDown')
    await expect(input).toHaveValue('Alpha')
    await input.press('Enter'); await expect(input).toHaveValue('Beta')
    await expect(page.getByRole('status', {name: 'Local selected value'})).toHaveText('b')
    await input.fill(''); await input.press('Enter')
    expect(await input.evaluate(element => (element as HTMLInputElement).checkValidity())).toBe(false)
    const custom = page.getByRole('combobox', {name: 'Custom type'})
    await custom.fill('New exact type'); await custom.press('Tab')
    await expect(page.getByRole('status', {name: 'Custom selected value'})).toHaveText('New exact type')
    await custom.fill('Pointer custom type')
    await page.getByRole('textbox', {name: 'Before menu'}).click()
    await expect(page.getByRole('status', {name: 'Custom selected value'})).toHaveText('Pointer custom type')
})

