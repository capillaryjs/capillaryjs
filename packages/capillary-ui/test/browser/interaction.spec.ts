import {expect, test} from '@playwright/test'
import type {Route} from '@playwright/test'

test.beforeEach(async ({page}) => { await page.goto('/interaction.html') })

test('icon actions and externally busy collections preserve identity and selection', async ({page}) => {
    const action = page.getByRole('button', {name: 'Add item', exact: true})
    await action.click()
    await expect(action).toHaveAttribute('aria-busy', 'true')
    await expect(action).toBeDisabled()
    expect(await action.locator('cap-icon').evaluate(element => getComputedStyle(element).maskImage)).not.toBe('none')
    expect(await action.evaluate(element => getComputedStyle(element).animationName)).toBe('cap-working-progress')
    await page.getByRole('button', {name: 'Finish action', exact: true}).click()
    await expect(action).not.toHaveAttribute('aria-busy')
    await expect(action).toBeEnabled()

    await page.getByRole('button', {name: 'Start related work'}).click()
    const collections = page.locator('cap-listview, cap-treeview, cap-datatable')
    for (const collection of await collections.all()) {
        await expect(collection).toHaveAttribute('aria-busy', 'true')
        await expect(collection).toHaveAttribute('data-cap-retained-loading', '')
        expect(await collection.evaluate(element => getComputedStyle(element, '::after').animationName)).toBe('cap-working-progress')
    }
    await page.getByRole('option', {name: 'Two', exact: true}).click()
    await expect(page.getByRole('option', {name: 'Two', exact: true})).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('treeitem', {name: /One/}).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('treeitem', {name: /One/})).toHaveAttribute('aria-expanded', 'true')
    await page.getByRole('button', {name: 'Filter Name'}).click()
    const choices = page.getByRole('dialog', {name: 'Filter Name'}).getByRole('checkbox')
    await expect(choices).toHaveAttribute('aria-busy', 'true')
    await expect(choices).toBeEnabled()
    await page.keyboard.press('Escape')
    await page.getByRole('button', {name: 'Finish related work'}).click()
    for (const collection of await collections.all()) await expect(collection).not.toHaveAttribute('aria-busy')
})

test('anchored popup escapes clipping, follows scrolling and returns keyboard focus', async ({page}) => {
    await page.setViewportSize({width: 375, height: 700})
    const anchor = page.getByRole('button', {name: 'Connect node'})
    await anchor.click()
    const panel = page.getByRole('dialog', {name: 'New connection'})
    await expect(panel).toBeVisible()
    await expect(panel.getByRole('textbox', {name: 'Target'})).toBeFocused()
    const before = await panel.boundingBox()
    expect(before!.x).toBeGreaterThanOrEqual(7)
    expect(before!.x + before!.width).toBeLessThanOrEqual(368)
    expect(await panel.evaluate(element => element.matches(':popover-open'))).toBe(true)
    const families = await Promise.all([panel, page.locator('cap-app')].map(locator => locator.evaluate(element => getComputedStyle(element).fontFamily)))
    expect(families[0]).toBe(families[1])
    await page.evaluate(() => window.scrollBy(0, 40))
    await expect.poll(async () => (await panel.boundingBox())!.y).not.toBe(before!.y)
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0)
    await expect(anchor).toBeFocused()
    await anchor.click()
    await expect(panel).toBeVisible()
    await page.getByRole('textbox', {name: 'Outside control'}).click()
    await expect(panel).toHaveCount(0)
    await expect(page.getByRole('textbox', {name: 'Outside control'})).toBeFocused()
})

test('stylesheet choice waits for the actual browser resource and offers retry after failure', async ({page}) => {
    let slow: Route | null = null, attempts = 0
    await page.route('**/fixture-slow.css', route => { slow = route })
    await page.route('**/fixture-failed.css', async route => {
        if (++attempts === 1) await route.abort('failed')
        else await route.fulfill({contentType: 'text/css', body: ':root { --interaction-theme-loaded: recovered; }'})
    })
    const theme = page.getByRole('combobox', {name: 'Theme', exact: true})
    await expect(theme).not.toHaveAttribute('aria-busy')
    await theme.selectOption('slow')
    await expect(theme).toHaveAttribute('aria-busy', 'true')
    await expect(theme).toBeEnabled()
    await expect.poll(() => slow != null).toBe(true)
    await (slow as unknown as Route).fulfill({contentType: 'text/css', body: ':root { --interaction-theme-loaded: slow; }'})
    await expect(theme).not.toHaveAttribute('aria-busy')
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--interaction-theme-loaded').trim())).toBe('slow')
    const size = await theme.locator('xpath=../..').boundingBox()
    await theme.selectOption('failed')
    await expect(theme).toHaveAttribute('aria-invalid', 'true')
    expect((await theme.locator('xpath=../..').boundingBox())!.height).toBe(size!.height)
    await page.getByRole('button', {name: 'Retry stylesheet'}).click()
    await expect(theme).not.toHaveAttribute('aria-busy')
    await expect(theme).not.toHaveAttribute('aria-invalid')
    expect(attempts).toBe(2)
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--interaction-theme-loaded').trim())).toBe('recovered')
})
